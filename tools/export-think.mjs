/**
 * Folds the prepared thinking-level artwork into a source constant.
 *
 * The client bundle cannot read files at runtime, so every panel background has to
 * travel inside it. This tool base64s the alpha WebPs in `assets/think/cutout` into
 * `src/think.js`; `build.mjs` then concatenates that file into `lib/client.js`.
 * Re-run after `node tools/prepare-think.py`, then rebuild.
 *
 *   node tools/export-think.mjs           # write src/think.js
 *   node tools/export-think.mjs --check   # compare only (tests)
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const LEVELS = ['off', 'low', 'high', 'max'];
const ART = new URL('../assets/think/cutout/', import.meta.url);
const TARGET = new URL('../src/think.js', import.meta.url);
const check = process.argv.includes('--check');

const entries = [];
for (const level of LEVELS) {
  let bytes;
  try {
    bytes = await readFile(new URL(`${level}.webp`, ART));
  } catch {
    throw new Error(`assets/think/cutout/${level}.webp is missing; run python tools/prepare-think.py`);
  }
  // Guard: a full-resolution PNG here would bloat the bundle by megabytes.
  if (bytes.length > 220 * 1024) throw new Error(`assets/think/cutout/${level}.webp is ${(bytes.length / 1024).toFixed(0)} KB; re-export it at 780px wide`);
  entries.push(`  ${level}: 'data:image/webp;base64,${bytes.toString('base64')}',`);
}

const source = `/** Generated by tools/export-think.mjs from assets/think/cutout — do not edit.
 *
 * One cutout per reasoning level, inlined because the client bundle cannot read the
 * plugin's files at runtime. Regenerate with \`python tools/prepare-think.py\` and
 * \`node tools/export-think.mjs\` after replacing the artwork. */
const THINK_ART = Object.freeze({
${entries.join('\n')}
});
`;

let current = '';
try {
  current = await readFile(TARGET, 'utf8');
} catch {}
if (current === source) {
  console.log('src/think.js: up to date');
} else if (check) {
  console.error('src/think.js: out of date with assets/think/cutout (run node tools/export-think.mjs)');
  process.exitCode = 1;
} else {
  await writeFile(TARGET, source);
  const kilobytes = Math.round(source.length / 1024);
  console.log(`src/think.js: written (${kilobytes} KB, ${fileURLToPath(TARGET)})`);
}
